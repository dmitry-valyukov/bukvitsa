#pragma once

#include "async.h"

namespace bukvitsa {

/// Подделка вёрстки: книга из блоков, страница — сколько-то блоков подряд.
///
/// Всё, что здесь важно, — что вёрстка блока стоит времени, а раскладка
/// целиком зависит от кегля, ширины окна и полей: изменилось любое из них —
/// посчитанное можно выбрасывать.
struct Layout {
    int fontSize = 11;      ///< кегль: меняется — меняется и всё остальное
    int blocks = 600;       ///< блоков в книге
    int blocksPerPage = 8;  ///< сколько блоков помещается на страницу
    int readingBlock = 240; ///< место, на котором читатель остановился
};

/// Что пагинация успела насчитать.
struct Pages {
    int blocksDone = 0;      ///< сколько блоков сверстано
    int counted = 0;         ///< сколько страниц из них получилось
    bool wholeBook = false;  ///< дошли ли до конца книги
};

/// Пагинация книги в потоке GUI — асинхронная, но никуда не уезжающая.
///
/// Три части, о которых шла речь, здесь идут одним циклом, и это не экономия
/// строк: прерывание в них обязано работать одинаково, а одинаково оно работает
/// тогда, когда механизм у них буквально один. Сперва верстается всё до места
/// чтения; на нём страница показывается; дальше тот же цикл доверстывает
/// остаток «в фоне».
///
/// Отмена проверяется на каждой передышке и отдельно — перед показом страницы:
/// пока считали, читатель мог потянуть за угол окна, и показывать посчитанное
/// по старой ширине нельзя.
///
/// \param token право отменить: раскладка изменилась — считать надо заново.
io::managed_task paginate(const Layout& layout, Pages& pages, io::cancellation_token token);

}  // namespace bukvitsa
