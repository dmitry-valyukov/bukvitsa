#pragma once
// Системный диалог открытия книги.
//
// Именно системный COM-диалог (IFileOpenDialog), а не выборщик WinRT: тот
// пришёл бы в профиль проекции вместе со всем асинхронным аппаратом Windows
// Runtime, а нужен здесь один вопрос с одним ответом. Диалог модальный, и
// пока он открыт, читалке всё равно делать нечего.

#include <filesystem>

struct HWND__;

namespace bukvitsa::reader {

/// Спрашивает у читателя файл книги. Пустой путь значит «отказался».
///
/// @param owner окно, которому диалог модален; без него он умеет уйти за
///        окно приложения, и читатель решит, что ничего не произошло.
std::filesystem::path askForBook(HWND__* owner);

}  // namespace bukvitsa::reader
