#pragma once
// Обложки: снимок раскрытой книги и кривые его краёв, настроенные читателем.
//
// Встроенная тема с фотографией гнёт строки идеализацией — синусом, одним на
// все снимки. У настоящего снимка нелинейность своя: верхний и нижний край
// листа описывают лежащую на боку букву S, и её близко задают несколько
// точек. Обложка — это и есть снимок плюс такие точки; их расставляет мастер
// (skin_wizard.h), а вёрстка строит по ним карту изгиба вместо синуса.
//
// Все координаты — в долях ширины и высоты снимка, а не в пикселях: обложка
// не знает ни размера окна, ни масштаба экрана, и настройка, снятая в одном
// окне, верна в любом. Статья о самом изгибе — doc/page-warp.md.

#include <array>
#include <filesystem>
#include <span>
#include <string>
#include <string_view>
#include <vector>

namespace bukvitsa::reader {

/// Одна обложка. Имя вводит читатель, и оно же — ключ реестра: сохранить
/// обложку под старым именем значит заменить её.
struct Skin {
    /// Девять вертикалей, на каждой по точке верхнего и нижнего края. Пять
    /// точек хватило бы кривой, девять дают запас там, где S гнётся круче.
    static constexpr int kPoints = 9;

    std::wstring name;
    std::wstring image;   ///< имя файла-копии снимка в skinDirectory()

    std::array<float, kPoints> x;        ///< вертикали, доли ширины
    std::array<float, kPoints> top;      ///< верхний край, доли высоты
    std::array<float, kPoints> bottom;   ///< нижний край, доли высоты
};

/// Начальный отступ прямых краёв и крайних вертикалей от кромок снимка.
inline constexpr float kEdgeInset = 1.0f / 40.0f;

/// Докуда мастер разрешает утянуть точку края: от кромки до четверти высоты.
inline constexpr float kEdgeReach = 0.25f;

/// Ход вертикали вбок от начального места. Меньше половины шага между
/// вертикалями, поэтому пересечься они не могут.
inline constexpr float kLineReach = 1.0f / 30.0f;

/// Обложка с точками на начальных местах: края — прямые в `kEdgeInset` от
/// кромок, вертикали — от `kEdgeInset` до зеркального места равномерно, так
/// что средняя стоит ровно в центре.
Skin defaultSkin();

/// Кривая края через контрольные точки: значение в середине каждой из
/// `columns` колонок, в тех же долях высоты, что и точки. Катмулл-Ром с
/// зажатыми концами; левее первой точки и правее последней кривая держит их
/// значение.
///
/// @param xs вертикали по возрастанию; ys — значения края на них.
std::vector<float> sampleEdge(std::span<const float> xs, std::span<const float> ys, int columns);

/// Реестр обложек — skins.xml. Читается и пишется целиком, как и остальные
/// файлы читалки; байты приносит и уносит `Io`.
class Skins {
public:
    /// Версия формата: незнакомое игнорируется, а не роняет разбор.
    static constexpr int kVersion = 1;

    /// Разбирает skins.xml. Пусто или битое — реестр просто пуст: обложки не
    /// то, ради чего стоит не запуститься.
    void loadFrom(std::string xml);

    /// Текст skins.xml — то, что уходит в `Io::writeFile`.
    std::string toXml() const;

    const std::vector<Skin>& list() const { return skins_; }

    const Skin* find(std::wstring_view name) const;

    /// Добавляет обложку или заменяет одноимённую: имя — ключ.
    void put(Skin skin);

private:
    std::vector<Skin> skins_;
};

/// Путь к skins.xml.
std::filesystem::path skinsPath();

/// Каталог копий снимков. Копий, а не ссылок на оригинал: обложка не должна
/// умереть вместе с перемещённым или стёртым исходным файлом.
std::filesystem::path skinDirectory();

}  // namespace bukvitsa::reader
