#pragma once
// Обложки: снимок раскрытой книги и кривые его краёв, настроенные читателем.
//
// Встроенная тема с фотографией гнёт строки идеализацией — синусом, одним на
// все снимки. У настоящего снимка нелинейность своя, причём у каждой из
// четырёх границ — верха и низа левого и правого листа — своя собственная:
// лист лежит как лежит, и его края не обязаны повторять друг друга. Поэтому
// обложка хранит четыре независимые кривые, по пять точек каждая — столько
// хватает лежащей на боку букве S, которой края и описываются. Точки
// расставляет мастер (skin_wizard.h), а вёрстка строит по ним карту изгиба
// вместо синуса.
//
// Все координаты — в долях ширины и высоты снимка, а не в пикселях: обложка
// не знает ни размера окна, ни масштаба экрана, и настройка, снятая в одном
// окне, верна в любом. Статья о самом изгибе — doc/page-warp.md.

#include <array>
#include <filesystem>
#include <span>
#include <string>
#include <string_view>
#include <vector>

namespace bukvitsa::reader {

/// Кривая одной границы листа: пять точек, каждая со своими X и Y.
struct EdgeCurve {
    static constexpr int kPoints = 5;

    std::array<float, kPoints> x;   ///< по возрастанию, доли ширины
    std::array<float, kPoints> y;   ///< доли высоты
};

/// Одна обложка. Имя вводит читатель, и оно же — ключ реестра: сохранить
/// обложку под старым именем значит заменить её.
struct Skin {
    std::wstring name;
    std::wstring image;   ///< имя файла-копии снимка в skinDirectory()

    EdgeCurve topLeft;
    EdgeCurve topRight;
    EdgeCurve bottomLeft;
    EdgeCurve bottomRight;
};

/// Начальный отступ прямых краёв и крайних точек кривой от кромок снимка.
inline constexpr float kEdgeInset = 1.0f / 40.0f;

/// Докуда мастер разрешает утянуть точку края: от кромки до четверти высоты.
inline constexpr float kEdgeReach = 0.25f;

/// Обложка с точками на начальных местах: края — прямые в `kEdgeInset` от
/// кромок, точки каждой кривой — равномерно по своей половине разворота, от
/// `kEdgeInset` у наружной кромки до `kEdgeInset` от корешка.
Skin defaultSkin();

/// Значение кривой края в точке `u` (доля ширины): Катмулл-Ром с зажатыми
/// концами; левее первой точки и правее последней кривая держит их значение.
float edgeAt(const EdgeCurve& curve, float u);

/// Реестр обложек — skins.xml. Читается и пишется целиком, как и остальные
/// файлы читалки; байты приносит и уносит `Io`.
class Skins {
public:
    /// Версия формата: незнакомое игнорируется, а не роняет разбор. Вторая —
    /// четыре независимые кривые вместо девяти общих вертикалей первой.
    static constexpr int kVersion = 2;

    /// Разбирает skins.xml. Пусто или битое — реестр просто пуст: обложки не
    /// то, ради чего стоит не запуститься.
    void loadFrom(std::string xml);

    /// Текст skins.xml — то, что уходит в `Io::writeFile`.
    std::string toXml() const;

    const std::vector<Skin>& list() const { return skins_; }

    const Skin* find(std::wstring_view name) const;

    /// Добавляет обложку или заменяет одноимённую: имя — ключ.
    void put(Skin skin);

private:
    std::vector<Skin> skins_;
};

/// Путь к skins.xml.
std::filesystem::path skinsPath();

/// Каталог копий снимков. Копий, а не ссылок на оригинал: обложка не должна
/// умереть вместе с перемещённым или стёртым исходным файлом.
std::filesystem::path skinDirectory();

}  // namespace bukvitsa::reader
