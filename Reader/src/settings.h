#pragma once
// Настройки читалки: то, чем открыться и как читать.
//
// Файл нарочно минимальный. На него опирается быстрый путь запуска: если
// читатель велел продолжать чтение, читается только он — реестр книг не
// трогается вовсе. Всё остальное (витрина, обложки, оглавление) живёт в
// library.xml и файлах книг и читается тогда, когда понадобится.
//
// Формат — XML, разбираемый wxl::xml: читатель у нас свой, оттестированный и
// на критическом пути ради FB3, а память берёт из STA-пула, который в main()
// всё равно создаётся. Запись своя, тридцать строк, потому что формат наш.

#include <filesystem>
#include <string>
#include <string_view>

namespace bukvitsa::reader {

/// Всё, что лежит в settings.xml.
struct Settings {
    /// Версия формата. Незнакомые элементы игнорируются молча, а не роняют
    /// разбор, — это она и покупает. Вторая версия пишет интерлиньяж и поля
    /// как есть, дробью; первая писала их сотыми долями целым числом, и
    /// разница видна только тому, кто такой файл читает.
    static constexpr int kVersion = 2;

    /// Где стояло окно и в каком было состоянии. Текст непрозрачный: его
    /// выдаёт и принимает обратно wxl (см. wxl::window_placement), а читалке
    /// достаточно донести его от файла до окна и обратно.
    std::wstring windowPlacement;

    /// Продолжать чтение при старте, минуя стартовый экран. По умолчанию
    /// снято: первый запуск показывает заставку с кнопками.
    bool continueReading = false;

    /// Как набирать книгу. Настройки чтения общие для всех книг, а не свои у
    /// каждой: читателю нужен один привычный вид, а не разный шрифт в каждой
    /// книге. Кегль в DIP, интерлиньяж и поля — в кеглях.
    int theme = 0;
    float fontSize = 20.0f;
    float lineHeight = 1.45f;
    float margin = 3.0f;

    /// Последняя книга — её guid в реестре и путь к файлу. Путь здесь копия
    /// того, что лежит в реестре, и копия намеренная: она и покупает быстрый
    /// путь. Протухла — спросим реестр по guid.
    std::wstring lastBookGuid;
    std::wstring lastBookPath;
};

/// Каталог данных читалки: `%LOCALAPPDATA%\Bukvitsa\Reader`.
///
/// Корень общий для семейства — рядом однажды встанет Writer. Не Roaming:
/// в реестре лежат локальные пути и кэш обложек, и роуминг перенёс бы на
/// другую машину битые ссылки и лишние мегабайты.
std::filesystem::path dataDirectory();

/// Путь к settings.xml.
std::filesystem::path settingsPath();

/// Разбирает settings.xml. Пусто, битое или от будущей версии — вернутся
/// значения по умолчанию: настройки не то, ради чего стоит не запуститься.
///
/// Разбор, а не чтение: байты приносит `Io::readFile`, потому что читать их
/// в интерфейсном потоке нельзя, а разбирать -- только в нём (память разбора
/// из STA-пула).
Settings parseSettings(std::string xml);

/// Текст settings.xml -- то, что уходит в `Io::writeFile`.
///
/// Атомарность здесь не педантизм: файл переписывается при каждом закрытии
/// окна, и падение посреди записи стоило бы читателю всего, что в нём есть.
std::string settingsXml(const Settings& settings);

}  // namespace bukvitsa::reader
