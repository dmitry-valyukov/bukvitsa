#pragma once
// Реестр книг: что читалка знает о книге, не открывая её.
//
// Отдельный файл, а не часть settings.xml, и это разделение по частоте и по
// цене: настройки читаются на каждом запуске и должны быть крошечными, а
// реестр — на каждой книге по строке метаданных, и нужен он только тогда,
// когда показывают витрину или ищут книгу по guid.
//
// Файл — это XML сегодня и, вероятно, база данных когда-нибудь потом. Поэтому
// снаружи виден список записей и поиск, а не «открой файл и почитай»: замена
// хранилища не должна дойти до тех, кто реестром пользуется.
//
// **У книги две личности.** `bookId` — UUID из самой книги: он один и тот же
// в двух копиях файла и не меняется, когда файл переезжает. `guid` — наш, и
// он выдаётся записи реестра: под этим именем лежит файл состояния чтения.
// Разные они потому, что книга без UUID тоже бывает, а место чтения ей всё
// равно нужно где-то держать.

#include <cstdint>
#include <filesystem>
#include <optional>
#include <string>
#include <vector>

namespace bukvitsa::reader {

class Book;

/// Одна книга в реестре — ровно то, что нужно витрине и быстрому запуску.
struct BookEntry {
    std::wstring guid;      ///< наш идентификатор; он же имя файла состояния
    std::wstring path;      ///< где лежит файл; книга остаётся на месте
    std::wstring bookId;    ///< UUID книги из FB3, если он у неё есть
    std::wstring title;
    std::wstring authors;
    std::wstring cover;    ///< имя файла обложки в cache, пусто -- обложки нет
    std::uint64_t fileSize = 0;        ///< вместе с path — дешёвая проверка «тот же файл»
    std::uint32_t characterCount = 0;  ///< знаменатель прогресса чтения
};

class Library {
public:
    /// Версия формата: незнакомое игнорируется, а не роняет разбор.
    static constexpr int kVersion = 1;

    /// Читает library.xml. Файла нет — реестр просто пуст.
    void load();

    /// Пишет library.xml через временный файл с заменой.
    bool save() const;

    const std::vector<BookEntry>& books() const { return books_; }

    const BookEntry* find(std::wstring_view guid) const;

    /// Та же книга, если она уже в реестре: сперва по UUID книги, потом по
    /// пути. Добавить книгу дважды нельзя — иначе у одной книги оказалось бы
    /// два места чтения, и читатель терял бы то из них, которое реже открывал.
    const BookEntry* findSame(const BookEntry& candidate) const;

    /// Добавляет книгу или обновляет уже известную, и отдаёт запись в реестре.
    /// Обновляет намеренно: файл могли переложить, а название — поправить в
    /// новом издании. Заодно кладёт обложку в кэш, потому что только здесь
    /// сходятся открытая книга и guid, под которым обложке лежать.
    const BookEntry& add(const Book& book);

private:
    std::vector<BookEntry> books_;
};

/// Новый guid записи реестра, в фигурных скобках, как их пишет Windows.
std::wstring newGuid();

/// Каталог, в котором лежат обложки. Отдельно от books намеренно: обложку
/// можно смело стереть -- она восстановится из книги, — а место чтения нельзя.
std::filesystem::path coverDirectory();

/// Закладка: место в книге и то, по чему читатель его узнает.
///
/// Подсказка — первые слова абзаца, а не номер страницы: страница меняется от
/// кегля и окна, слова не меняются. По той же причине место хранится символом.
struct Bookmark {
    std::uint32_t charOffset = 0;
    std::wstring hint;
};

/// Всё, что читалка помнит про одну книгу: books\{guid}.xml.
///
/// Отдельный файл на книгу, а не строка в реестре, потому что растёт он
/// по-другому: закладок у любимой книги бывает больше, чем всего остального
/// в реестре, — а читаются они только когда книгу открыли.
///
/// Читается и пишется целиком, одной штукой. Иначе запись места чтения
/// затирала бы закладки: файл переписывается заменой, и «дописать в него
/// одно поле» — это всё равно написать его весь.
struct BookState {
    static constexpr int kVersion = 1;

    std::uint32_t charOffset = 0;
    std::vector<Bookmark> bookmarks;

    /// Есть ли закладка на этом месте. Совпадение точное: закладку ставят на
    /// начало страницы, и оно же приходит обратно.
    bool hasBookmark(std::uint32_t offset) const;
};

BookState loadBookState(std::wstring_view guid);
bool saveBookState(std::wstring_view guid, const BookState& state);

}  // namespace bukvitsa::reader
