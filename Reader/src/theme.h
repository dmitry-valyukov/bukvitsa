#pragma once
// Оформление полосы. Три темы, как у лампы три яркости.
//
// Цвета подобраны так, чтобы контраст текста к фону был ниже, чем чёрное по
// белому: страница бумажной книги отражает от 70 до 85 процентов света, а не
// сто, и глаз к этому привык. Чистый белый фон на экране читается как лист,
// подсвеченный изнутри, — от него устают.
//
// Цвета сразу в том виде, в каком их берёт Direct2D: полосу рисуем мы сами, и
// переводить их по дороге незачем.

#include <d2d1.h>

namespace bukvitsa::reader {

struct Theme {
    const wchar_t* name;
    D2D1_COLOR_F background;
    D2D1_COLOR_F text;
    D2D1_COLOR_F dim;      ///< колонцифра и прогресс — тише основного текста
    D2D1_COLOR_F panel;    ///< подложка сноски и панели: чуть иначе, чем полоса

    /// Цвет теней: средника, сгиба, поднятой бумаги. Глубоко коричневый, а не
    /// чёрный — бумага не отражает свет ровно, и тень на ней уходит в тон
    /// самой бумаги, а не в серое. Тёмный настолько, что вблизи чёрного:
    /// разница должна читаться теплом, а не бурым налётом. Прозрачность у
    /// каждой тени своя, здесь только тон.
    ///
    /// Он в теме, а не общей константой, из-за ночной полосы. Там затемнять в
    /// бумаге нечего, она и так почти чёрная, — тень работает на буквах. Зато
    /// коричневый, годный дневной странице, лёг бы по такой бумаге бурой
    /// дымкой: он её светлее. Ночной тон поэтому темнее полосы, а тёплый он
    /// перевесом красного над синим — как и остальные два.
    D2D1_COLOR_F shadow;
};

/// Из восьмибитного цвета, каким его удобно записывать, в тот, каким его
/// хочет D2D. constexpr, поэтому таблица ниже остаётся таблицей.
constexpr D2D1_COLOR_F rgb(int r, int g, int b) {
    return {r / 255.0f, g / 255.0f, b / 255.0f, 1.0f};
}

inline constexpr Theme kThemes[] = {
    {L"День",  rgb(250, 248, 243), rgb(32, 30, 28),    rgb(150, 145, 138), rgb(236, 232, 224),
     rgb(28, 18, 10)},
    {L"Сепия", rgb(245, 233, 209), rgb(70, 52, 32),    rgb(160, 138, 106), rgb(232, 216, 186),
     rgb(34, 20, 8)},
    {L"Ночь",  rgb(24, 24, 26),    rgb(208, 204, 198), rgb(110, 108, 104), rgb(40, 40, 44),
     rgb(10, 6, 2)},
};

inline constexpr int kThemeCount = static_cast<int>(sizeof(kThemes) / sizeof(kThemes[0]));

}  // namespace bukvitsa::reader
