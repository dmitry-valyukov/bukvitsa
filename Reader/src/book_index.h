#pragma once
// Два способа найти в книге место: оглавление и поиск.
//
// Оба стоят на блоках, в которые вёрстка развернула книгу, и оба отдают одно
// и то же — позицию в символах. Дальше её принимает полоса набора, которая
// умеет спросить у пагинатора номер страницы; ни оглавление, ни поиск про
// страницы не знают вовсе и потому не портятся от смены кегля.
//
// Почему по блокам, а не по дереву книги: блоки уже есть, в них текст сплошной
// (свёртка пробелов сделана), а рядом с каждым символом лежит его позиция в
// книге. Обходить дерево заново значило бы повторить эту работу и получить
// другие индексы.

#include <cstdint>
#include <span>
#include <string>
#include <string_view>
#include <vector>

#include "bukvitsa/typography/block.h"

namespace bukvitsa::reader {

/// Строка оглавления.
struct ContentsEntry {
    std::wstring title;
    std::uint8_t level = 0;        ///< глубина секции: 0 — часть, дальше главы
    std::uint32_t charOffset = 0;
};

/// Оглавление книги: заголовки в порядке чтения.
///
/// Книга без заголовков бывает — тогда оглавление пустое, и показывать нечего.
/// Выдумывать вместо него список абзацев не нужно: пустое оглавление честнее
/// длинного списка ни о чём.
std::vector<ContentsEntry> contentsOf(std::span<const typography::Block> blocks);

/// Находка поиска: место и кусок текста вокруг него.
struct SearchHit {
    std::wstring context;          ///< отрывок абзаца, в котором нашлось
    std::uint32_t charOffset = 0;  ///< позиция самой находки в книге
};

/// Ищет по книге, не различая регистра.
///
/// @param limit сколько находок вернуть. Ограничение не от лени: «а» в романе
///        встречается десятки тысяч раз, и список из них бесполезен читателю
///        ровно так же, как дорог приложению.
std::vector<SearchHit> searchBook(std::span<const typography::Block> blocks,
                                  std::wstring_view needle, std::size_t limit = 200);

/// Первые слова абзаца, в котором стоит эта позиция, — подсказка для закладки.
std::wstring hintAt(std::span<const typography::Block> blocks, std::uint32_t charOffset);

}  // namespace bukvitsa::reader
