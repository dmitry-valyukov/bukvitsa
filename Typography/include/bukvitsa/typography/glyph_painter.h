#pragma once
// Отрисовка того, что навёрстано: прогон глифов и строка целиком.
//
// Живёт в Typography, а не в приложении, потому что перевод прогона глифов в
// вызов Direct2D — вторая половина той же работы: кто разложил глифы по
// строке, тот и знает, как их нарисовать. Приложениям остаётся решить, где и
// каким цветом, а это уже не сюда.
//
// Кисть и контекст приходят снаружи, и откуда они взялись — не наше дело:
// ни полей, ни тем, ни решений о том, что показывать, здесь нет. Это и держит
// границу слоёв: D2D — API отрисовки того же уровня, что DirectWrite, которую
// Typography и так знает, а вот окна ей по-прежнему неизвестны.

// Через layout.h, а тот — через block.h: там собрано объединение стандартных
// заголовков всех публичных заголовков вёрстки и стоит импорт, после которого
// стандартный заголовок MSVC уже не примет.
#include "bukvitsa/typography/layout.h"

namespace bukvitsa::typography {

/// Рисует прогон глифов; x — левый край прогона, baseline — базовая линия.
///
/// Подчёркивание и зачёркивание чертятся здесь же по метрикам шрифта: в самом
/// шрифте их нет, а место и толщину знает только он.
void drawGlyphRun(ID2D1DeviceContext* context, const GlyphRun& run, float x, float baseline,
                  ID2D1Brush* brush);

/// Рисует строку целиком: originX прогонов отсчитывается от x.
void drawLine(ID2D1DeviceContext* context, const Line& line, float x, float baseline,
              ID2D1Brush* brush);

}  // namespace bukvitsa::typography
